    // `config.toml` carries the run's model and x-sc-* attribution headers, and
    // codex reads it at startup, so two runs must not share one durable directory.
    #[test]
    fn a_second_run_does_not_share_a_durable_state_dir() {
        let dir = TempDir::new().unwrap();
        let path = dir.path().join("state");
        let first = CodexHome::prepare(Some(path.to_str().unwrap()), false).expect("first");
        assert!(first.is_durable());
        assert!(
            path.join("run.lock").is_file(),
            "the first run must hold a lock"
        );

        let second = CodexHome::prepare(Some(path.to_str().unwrap()), false).expect("second");
        assert!(
            !second.is_durable(),
            "the second run must fall back to a temp CODEX_HOME instead of sharing config.toml"
        );
        assert_ne!(second.path(), first.path());

        // Ownership is the `flock`, not the file: the lock file stays put and the
        // claim ends when the holder drops. There is therefore no staleness to age
        // out and no window in which two runs both decide a lock is abandoned.
        drop(first);
        let third = CodexHome::prepare(Some(path.to_str().unwrap()), false).expect("third");
        assert!(
            third.is_durable(),
            "the directory must be reusable once the previous run releases it"
        );
        assert_eq!(third.path(), path.as_path());
    }

