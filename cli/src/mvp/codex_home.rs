    // The merge is the caller's easiest thing to forget, so `write_config` owns it:
    // the renderer is handed the preserved keys instead of a finished string.
    #[test]
    fn write_config_hands_the_renderer_the_preserved_keys() {
        let dir = TempDir::new().unwrap();
        let home = home_with(dir.path());
        home.write_config(|_| {
            "model = \"m\"\n\n[projects.\"/repo\"]\ntrust_level = \"trusted\"\n".to_string()
        })
        .unwrap();

        let mut seen = String::new();
        home.write_config(|preserved| {
            seen = preserved.tables.clone();
            format!("{GENERATED_MARKER}\nmodel = \"m2\"\n{}", preserved.tables)
        })
        .unwrap();
        assert!(
            seen.contains("[projects.\"/repo\"]"),
            "renderer saw: {seen}"
        );
        let after = fs::read_to_string(dir.path().join("config.toml")).unwrap();
        let parsed: toml::Table = toml::from_str(&after).unwrap();
        assert_eq!(
            parsed["projects"]["/repo"]["trust_level"].as_str(),
            Some("trusted")
        );
    }

